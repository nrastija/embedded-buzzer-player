void playPreviseSuza(int buzzer) {
  Track tr[6];
  initTrack(tr[0], melody0, NUM_OF_NOTES0);
  initTrack(tr[1], melody1, NUM_OF_NOTES1);
  initTrack(tr[2], melody2, NUM_OF_NOTES2);
  initTrack(tr[3], melody3, NUM_OF_NOTES3);
  initTrack(tr[4], melody4, NUM_OF_NOTES4);

  int16_t buf[64];
  size_t written;

  while (true) {
    if (stopPreviseSuzaPlaying) { stopPreviseSuzaPlaying = false; break; }
    if (stopRequested) break; 

    bool allDone = true;
    for (int i = 0; i < 64; i++) {
		if (checkStop()) return;   

      int32_t sum = 0;
      for (int t = 0; t < 5; t++) {
        sum += nextSample(tr[t]);
        if (!tr[t].done) allDone = false;
      }
      buf[i] = (int16_t)constrain(sum, -32768, 32767);
    }
    i2s_write(I2S_PORT, buf, sizeof(buf), &written, portMAX_DELAY);
    if (allDone) break;
  }
  i2s_zero_dma_buffer(I2S_PORT);
}

